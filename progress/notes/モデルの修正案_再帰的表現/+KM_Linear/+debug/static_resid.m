function [lhs, rhs] = static_resid(y, x, params)
T = NaN(2, 1);
lhs = NaN(10, 1);
rhs = NaN(10, 1);
T(1) = params(10)*params(4)*params(1)*(params(1)-1)*(params(10)+params(8))^(params(1)-2);
T(2) = params(10)*params(1)*params(2)*(params(10)+params(8))^(params(1)-1);
lhs(1) = params(12)*params(9)*y(3)+params(11)/params(4)*y(5)+params(13)*y(6);
rhs(1) = y(3)*(params(12)*params(9)+params(9)*(params(6)+params(7)))+params(11)*y(5);
lhs(2) = y(5);
rhs(2) = y(3)+y(1)-x(1);
lhs(3) = y(6);
rhs(3) = y(3);
lhs(4) = y(2);
rhs(4) = y(2)*params(5)/params(4)+1/params(4)*y(8);
lhs(5) = y(1)*params(12)*(1+params(16))+params(12)*y(2)+y(2)*params(7)*params(5);
rhs(5) = y(1)*params(12)*(params(5)*(1+params(16))+params(15))+y(2)*params(5)*(params(12)+params(6)+params(7))+y(8)*params(12)*params(15)-x(1)*params(12)*params(15);
lhs(6) = params(12)*y(1);
rhs(6) = T(1)*y(4)+y(1)*params(12)*params(4);
lhs(7) = params(13)*y(6)+params(2)*params(14)*y(7);
rhs(7) = y(3)*params(9)*(params(6)+params(7))+y(4)*T(2);
lhs(8) = params(9)*y(3)+y(4)*params(10)*params(2);
rhs(8) = 0;
lhs(9) = y(9);
rhs(9) = y(6)+params(2)*y(7);
lhs(10) = y(10);
rhs(10) = y(9);
end

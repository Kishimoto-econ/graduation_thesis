function [lhs, rhs] = static_resid(y, x, params)
T = NaN(2, 1);
lhs = NaN(20, 1);
rhs = NaN(20, 1);
T(1) = y(3)-1/params(2);
T(2) = 1/params(2)+T(1)*y(14);
lhs(1) = y(3)*y(4)+y(5)-y(2)*params(6);
rhs(1) = y(4)+y(2)*params(5);
lhs(2) = y(3)*y(4);
rhs(2) = y(1)*y(2);
lhs(3) = y(5);
rhs(3) = y(2)*params(6);
lhs(4) = 1+y(6);
rhs(4) = y(3)*(1+y(6))*params(1)+y(3)*y(7);
lhs(5) = y(1)*(1+y(6))+y(6)*params(6)*params(1);
rhs(5) = (1+y(6))*params(1)*(y(1)+params(6)+params(5))+y(1)*y(7);
lhs(6) = y(1);
rhs(6) = params(2)*(y(1)+params(4)*(params(7)+y(8))^(params(4)-1));
lhs(7) = y(10);
rhs(7) = (1-params(8))*params(3)*T(1)+y(10)*params(8)*params(3)*y(9);
lhs(8) = y(11);
rhs(8) = 1-params(8)+y(11)*params(8)*params(3)*y(12);
lhs(9) = y(14);
rhs(9) = y(11)/(params(10)-y(10));
lhs(10) = y(4);
rhs(10) = y(14)*y(13)*(1+y(20));
lhs(11) = y(20);
rhs(11) = params(17)*(y(1)-params(20))+params(18)*(y(13)-params(35))+params(19)*(y(4)-params(23));
lhs(12) = y(12);
rhs(12) = T(2);
lhs(13) = y(9);
rhs(13) = y(12);
lhs(14) = y(13);
rhs(14) = y(15)+y(16);
lhs(15) = y(15);

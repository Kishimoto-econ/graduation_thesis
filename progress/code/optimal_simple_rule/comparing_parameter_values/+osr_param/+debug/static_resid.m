lhs(16) = y(16);
rhs(16) = y(4)*params(9);
lhs(17) = y(3)*y(4)+y(5)+params(11)*y(17)+params(11)*y(18)/params(2);
rhs(17) = y(19)+y(4)*params(11)*(1-params(8)-params(9));
lhs(18) = y(19);
rhs(18) = y(2)*(params(6)+params(5))+params(11)*(params(7)+y(8))^params(4);
lhs(19) = y(2)+y(8)*params(11);
rhs(19) = params(12);
lhs(20) = y(4)+params(11)*y(18);
rhs(20) = y(13);
end
